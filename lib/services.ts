/** Блок SEO-текста на странице услуги (рендерится после блока «Что входит в работу») */
export type ServiceBlock =
  | { type: "h2"; text: string }
  | { type: "h3"; text: string }
  | { type: "p"; text: string }
  | { type: "ul"; items: string[] }
  | { type: "ol"; items: string[] };

export type Service = {
  slug: string;
  num: string;
  /** H1 страницы */
  h1: string;
  /** Title для метатегов */
  title: string;
  /** Description для метатегов */
  description: string;
  /** Ключевые слова страницы (низкочастотное ядро кластера) */
  keywords: string[];
  /** Краткое описание для карточки на хабе */
  short: string;
  /** Цена на карточке */
  price: string;
  unit: string;
  tag: string | null;
  /** Вводный лида-абзац */
  lead: string;
  /** Что входит в работу */
  scope: { title: string; body: string }[];
  /** Ценовые сегменты (таблица прайса на странице) */
  priceRows: { name: string; price: string }[];
  /** Технологии и факты: блок цифр */
  facts: { n: string; l: string }[];
  /** FAQ для JSON-LD FAQPage */
  faq: { q: string; a: string }[];
  /** Связанные услуги (slug): перелинковка */
  related: string[];
  /** География для текстового блока */
  geo: string;
  /** Минимальная цена в BYN: для Offer в JSON-LD */
  priceFrom: number;
  /** SEO-текст страницы (технологии, случаи, цены) */
  content?: ServiceBlock[];
};

